// Bundles the shared pattern spec (patterns/*.json) and the sample texts
// (samples/) into plain scripts the browser app can load. The page's
// Content-Security-Policy blocks fetch(), so data has to ship as script.
//
//   node scripts/build-web.mjs           write web/patterns.js and web/samples.js
//   node scripts/build-web.mjs --check   fail if those files are out of date (CI)

import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const version = readFileSync(join(root, "src/local_redact/__init__.py"), "utf8").match(
  /__version__ = "([^"]+)"/
)[1];

const detectors = readdirSync(join(root, "patterns"))
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => JSON.parse(readFileSync(join(root, "patterns", f), "utf8")))
  .sort((a, b) => a.order - b.order);

const samples = JSON.parse(readFileSync(join(root, "samples/index.json"), "utf8")).map((s) => ({
  ...s,
  text: readFileSync(join(root, "samples", s.file), "utf8"),
}));

function umd(globalName, header, value) {
  return (
    `// ${header}\n// Generated by scripts/build-web.mjs. Do not edit by hand.\n` +
    `(function (root) {\n` +
    `  var DATA = ${JSON.stringify(value, null, 2).replace(/\n/g, "\n  ")};\n` +
    `  if (typeof module === "object" && module.exports) module.exports = DATA;\n` +
    `  else root.${globalName} = DATA;\n` +
    `})(typeof self !== "undefined" ? self : this);\n`
  );
}

const outputs = {
  "web/patterns.js": umd("LOCAL_REDACT_SPEC", "Built-in detectors, from patterns/*.json.", { version, detectors }),
  "web/samples.js": umd("LOCAL_REDACT_SAMPLES", "Synthetic sample texts, from samples/.", samples),
};

let stale = [];
for (const [rel, content] of Object.entries(outputs)) {
  const path = join(root, rel);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  if (check) stale.push(rel);
  else {
    writeFileSync(path, content);
    console.log(`wrote ${rel}`);
  }
}
if (stale.length) {
  console.error(`Out of date: ${stale.join(", ")}. Run: node scripts/build-web.mjs`);
  process.exit(1);
}
if (check) console.log("web bundle is up to date");
